def store(tmp_path, layers=None, name=("registry.ollama.ai", "library", "tiny", "latest"), **kw):
    blobs = tmp_path / "models" / "blobs"
    blobs.mkdir(parents=True, exist_ok=True)
    model = write_tiny_llama(blobs / f"sha256-{DIGEST}", **kw)
    manifest = tmp_path / "models" / "manifests" / os.path.join(*name)
    manifest.parent.mkdir(parents=True, exist_ok=True)
    layers = layers or [{"mediaType": "application/vnd.ollama.image.model", "digest": f"sha256:{DIGEST}"}]
    manifest.write_text(json.dumps({"layers": layers}))
    return model


def show(model, extra="") -> dict:
    return {
        "modelfile": f'# Modelfile generated by "ollama show"\n# FROM tiny:latest\n\nFROM {model}\n{extra}TEMPLATE x\n',
        "capabilities": ["completion"],
        "details": {"format": "gguf"},
    }


def test_locates_the_blob_from_the_modelfile(tmp_path):
    model = store(tmp_path)
    files = locate(show(model), "tiny")
    assert files.path == model and files.digest == DIGEST and not files.vision
    assert files.gguf.block_count == 4


def test_projector_is_noticed(tmp_path):
    proj = "cd" * 32
    model = store(
        tmp_path,
        layers=[
            {"mediaType": "application/vnd.ollama.image.model", "digest": f"sha256:{DIGEST}"},
            {"mediaType": "application/vnd.ollama.image.projector", "digest": f"sha256:{proj}"},
        ],
    )
    files = locate(show(model, f"FROM {model.parent / ('sha256-' + proj)}\n"), "tiny")
    assert files.vision and files.projectors == [model.parent / f"sha256-{proj}"]


def test_manifest_fallback_without_a_from_line(tmp_path):
    model = store(tmp_path)
    data = show(model)
    data["modelfile"] = "TEMPLATE x\n"
    assert locate(data, "tiny", models_dirs=[tmp_path / "nowhere", tmp_path / "models"]).path == model


@pytest.mark.parametrize(
    "case,message",
    [
        ("sharded", "several files"),
        ("adapter", "adapter"),
        ("embedding", "not a text-generation model"),
        ("safetensors", "GGUF"),
        ("split_count", "several files"),
        ("missing", "could not find"),
    ],
)
def test_models_split_mode_cant_use(tmp_path, case, message):
    model_layer = {"mediaType": "application/vnd.ollama.image.model", "digest": f"sha256:{DIGEST}"}
    layers = None
    if case == "sharded":
        layers = [model_layer, {**model_layer, "digest": "sha256:" + "ef" * 32}]
    if case == "adapter":
        layers = [model_layer, {"mediaType": "application/vnd.ollama.image.adapter", "digest": "sha256:" + "ef" * 32}]
    model = store(tmp_path, layers=layers, extra_kv={"split.count": 2} if case == "split_count" else None)
    data = show(model)
    if case == "embedding":
        data["capabilities"] = ["embedding"]
    if case == "safetensors":
        data["details"]["format"] = "safetensors"
    if case == "missing":
        data["modelfile"] = ""
    with pytest.raises(ModelUnavailable, match=message):
        locate(data, "tiny", models_dirs=[tmp_path / "nowhere"])


@pytest.mark.skipif(sys.platform == "win32" or os.geteuid() == 0, reason="root can read anything")
def test_unreadable_blob_says_how_to_fix_it(tmp_path):
    model = store(tmp_path)
    model.chmod(0)
    with pytest.raises(ModelUnavailable, match="must be readable"):
        locate(show(model), "tiny")


def test_oversized_manifest_is_ignored(tmp_path):
    path = tmp_path / "manifests" / "registry.ollama.ai" / "library" / "x" / "latest"
    path.parent.mkdir(parents=True)
    path.write_text(" " * (2 * 1024 * 1024))
    assert read_manifest(tmp_path, "x") is None


