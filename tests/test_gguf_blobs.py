DIGEST = "ab" * 32


def test_reads_layers_and_attention_shape(tmp_path):
    info = read_gguf(write_tiny_llama(tmp_path / "m.gguf", n_layer=3, n_embd=64, n_head=4, n_head_kv=2, n_ff=128))
    assert (info.architecture, info.block_count, info.head_count, info.head_count_kv) == ("llama", 3, 4, 2)
    assert info.context_length == 512 and info.embedding_length == 64
    assert info.feed_forward_length == 128 and info.vocab_size == len(vocab()[0])  # from token_embd's shape
    per_layer = 4 * (64 + 64 * 64 + 2 * 64 * 32 + 64 * 64 + 64 + 3 * 64 * 128)  # F32 weights of one block
    assert info.layer_bytes == [per_layer] * 3
    vocab_bytes = 4 * 64 * len(vocab()[0])
    assert info.input_bytes == vocab_bytes
    assert info.output_bytes == vocab_bytes + 4 * 64  # output.weight + output_norm
    assert info.weights_bytes <= info.file_size
    # K and V heads of 16 values, 2 KV heads, f16: 128 bytes per token per layer
    assert info.kv_bytes_per_layer(1000) == 1000 * 2 * (16 + 16) * 2


def test_tied_embeddings_count_for_the_output_layer(tmp_path):
    info = read_gguf(write_tiny_llama(tmp_path / "m.gguf", tied=True))
    assert info.output_bytes == info.input_bytes + 4 * 64


def test_sharded_marker_is_read(tmp_path):
    info = read_gguf(write_tiny_llama(tmp_path / "m.gguf", extra_kv={"split.count": 3}))
    assert info.split_count == 3


@pytest.mark.parametrize(
    "mutate,message",
    [
        (lambda b: b"GGML" + b[4:], "not a GGUF"),
        (lambda b: b[:4] + struct.pack("<I", 9) + b[8:], "version"),
        (lambda b: b[:200], "truncated"),
        (lambda b: b[:8] + struct.pack("<Q", 10**9) + b[16:], "implausible"),
    ],
)
def test_bad_files_are_refused(tmp_path, mutate, message):
    path = write_tiny_llama(tmp_path / "m.gguf")
    path.write_bytes(mutate(path.read_bytes()))
    with pytest.raises(GGUFError, match=message):
        read_gguf(path)


def test_huge_string_length_is_refused_before_reading(tmp_path):
    path = tmp_path / "m.gguf"
    path.write_bytes(b"GGUF" + struct.pack("<IQQ", 3, 0, 1) + struct.pack("<Q", 2**40))
    with pytest.raises(GGUFError, match="too long"):
        read_gguf(path)


